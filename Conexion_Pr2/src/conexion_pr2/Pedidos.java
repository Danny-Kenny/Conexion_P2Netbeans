    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            double total = Double.parseDouble(jTextField1.getText().trim());
            int idCliente = Integer.parseInt(jTextField2.getText().trim());
            
            // Llamada al Procedimiento Almacenado
            if (BD.CALLPedido(total, idCliente)) {
                JOptionPane.showMessageDialog(this, "Pedido insertado correctamente.");
                base.refrescar(); // Refresca la tabla principal en BASE
                limpiarCampos();
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Verifica que el Total y el ID Cliente sean números válidos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // Pedimos el ID del pedido a modificar por medio de un cuadro de diálogo
            String idStr = JOptionPane.showInputDialog(this, "Ingresa el ID del Pedido a actualizar:");
            if (idStr == null || idStr.trim().isEmpty()) return;
            
            int idPedido = Integer.parseInt(idStr);
            double total = Double.parseDouble(jTextField1.getText().trim());
            int idCliente = Integer.parseInt(jTextField2.getText().trim());
            
            // Llamada al método de actualización en SQL_Conexion
            if (BD.updatePedido(idPedido, total, idCliente)) {
                JOptionPane.showMessageDialog(this, "Pedido actualizado correctamente.");
                base.refrescar();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró el pedido con ese ID.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Verifica que los datos numéricos sean correctos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void limpiarCampos() {
        jTextField1.setText("");
        jTextField2.setText("");
    }
    

