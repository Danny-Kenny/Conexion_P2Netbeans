    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String ID = jTextField1.getText().trim();
        if (ID.isEmpty()) {
            // Si está vacío, recarga toda la tabla del módulo actual
            base.refrescar(); 
            return;
        }
        
        try {
            Integer.parseInt(ID); // Validar que sea número
            // (Aquí podrías implementar un filtro en específico en el futuro)
            base.refrescar();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Los ID son únicamente números enteros", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String ID = jTextField1.getText().trim();
        if (ID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Advertencia: Ingresa un ID para eliminar", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            int id = Integer.parseInt(ID);
            int confirmacion = JOptionPane.showConfirmDialog(this, "¿Seguro que deseas eliminar el registro #" + id + " en " + base.moduloActual + "?", "Confirmación", JOptionPane.YES_NO_OPTION);
            
            if (confirmacion == JOptionPane.YES_OPTION) {
                // Llamamos a la ventana BASE para que ejecute el borrado correspondiente
                boolean exito = base.eliminarID(id, base.moduloActual);
                if (exito) {
                    JOptionPane.showMessageDialog(this, "Registro eliminado exitosamente.");
                    jTextField1.setText("");
                } else {
                    JOptionPane.showMessageDialog(this, "No se pudo eliminar. Verifica que el ID exista o no tenga registros dependientes.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Los ID son únicamente números enteros", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed


