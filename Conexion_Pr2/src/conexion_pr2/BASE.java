    private void M_Panel (JPanel contenedor, JPanel contenido){
        contenedor.removeAll();
        contenedor.setLayout(new BorderLayout());
        contenedor.add(contenido, BorderLayout.CENTER);
        contenedor.revalidate();
        contenedor.repaint();
    }
    
    public void cambiarModulo (String name, JPanel formulario){
        this.moduloActual = name;
        M_Panel(jPanel2, formulario);
        refrescar();
    }
    
    public void refrescar(){
         switch (moduloActual) {
            case "Cliente" -> jTable1.setModel(BD.mostrarClientes(""));
            case "Pedido" -> jTable1.setModel(BD.mostrarPedidos(""));
            case "Producto" -> jTable1.setModel(BD.mostrarProductos(""));
            case "Detalle" -> jTable1.setModel(BD.mostrarDetPedido(""));
        }
    }
    
    
    public boolean eliminarID(int id, String modulo) {
        boolean exito = false;
        switch (modulo) {
            case "Cliente" -> exito = BD.deleteCliente(id);
            case "Pedido" -> exito = BD.deletePedido(id);
            case "Producto" -> exito = BD.deleteProducto(id);
            case "Detalle" -> exito = BD.deleteDetalle(id);
        }
        if (exito) refrescar();
        return exito;
    }
    
