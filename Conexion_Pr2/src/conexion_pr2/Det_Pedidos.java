    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            // Obtenemos la cantidad del JSpinner (si usaste un JTextField, usa Integer.parseInt(txtCantidad.getText()))
            int cantidad = (Integer) jSpinner1.getValue(); 
            
            double precioUnitario = Double.parseDouble(jTextField2.getText().trim());
            int idPedido = Integer.parseInt(jTextField3.getText().trim());
            int idProducto = Integer.parseInt(jTextField4.getText().trim());

            // Llamada al Procedimiento Almacenado
            if (BD.CALLDet_Pedido(cantidad, precioUnitario, idPedido, idProducto)) {
                JOptionPane.showMessageDialog(this, "Detalle de pedido insertado correctamente.");
                base.refrescar(); // Refresca la tabla principal
                limpiarCampos();
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Verifica que Precio, ID Pedido y ID Producto sean números válidos.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error inesperado: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            String idStr = JOptionPane.showInputDialog(this, "Ingresa el ID del detalle a actualizar:");
            if (idStr == null || idStr.trim().isEmpty()) return;
            
            int idDetalle = Integer.parseInt(idStr);
            int cantidad = (Integer) jSpinner1.getValue();
            double precioUnitario = Double.parseDouble(jTextField2.getText().trim());
            int idPedido = Integer.parseInt(jTextField3.getText().trim());
            int idProducto = Integer.parseInt(jTextField4.getText().trim());
            
            if (BD.updateDetPedido(idDetalle, cantidad, precioUnitario, idPedido, idProducto)) {
                JOptionPane.showMessageDialog(this, "Detalle actualizado correctamente.");
                base.refrescar();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró el detalle con ese ID.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: Verifica que los datos numéricos sean correctos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void limpiarCampos() {
        jSpinner1.setValue(0); // Reinicia el spinner
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
    }
    
