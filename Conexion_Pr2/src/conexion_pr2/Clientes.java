    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String nombre = jTextField1.getText();
            String correo = jTextField2.getText();
            String direccion = jTextField3.getText();
            
            // Llamada al SP de inserción
            if (BD.CALLCliente(nombre, correo, direccion)) {
                JOptionPane.showMessageDialog(this, "Cliente insertado correctamente.");
                base.refrescar(); // Refresca la tabla en BASE
                limpiarCampos();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al insertar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // Para actualizar necesitas un ID. Asegúrate de tener un JTextField para el ID en el diseño.
            // Si no lo tienes, puedes agregarlo o usar un JOptionPane para pedirlo.
            String idStr = JOptionPane.showInputDialog(this, "Ingresa el ID del cliente a actualizar:");
            if (idStr == null || idStr.trim().isEmpty()) return;
            
            int id = Integer.parseInt(idStr);
            String nombre = jTextField1.getText();
            String correo = jTextField2.getText();
            String direccion = jTextField3.getText();
            
            if (BD.updateCliente(id, nombre, correo, direccion)) {
                JOptionPane.showMessageDialog(this, "Cliente actualizado correctamente.");
                base.refrescar();
                limpiarCampos();
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró el cliente.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número.");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void limpiarCampos() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
    }

